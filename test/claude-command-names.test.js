// test/claude-command-names.test.js
//
// Claude Code refuses a custom command named like one of its built-ins
// (owner, 2026-11-24: "Not loaded: a custom /ship. Rename it, then restart.").
// Carja's /ship becomes /ship-it and /status becomes /carja-status in Claude
// Code; the workflow file and other harnesses keep their names.

import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { generateClaudeCommands, CLAUDE_BUILTINS } from "../src/claude-commands.js";

function project() {
  const dir = mkdtempSync(join(tmpdir(), "claude-names-"));
  mkdirSync(join(dir, ".agents/workflows"), { recursive: true });
  for (const n of ["ship", "build"]) writeFileSync(join(dir, `.agents/workflows/${n}.md`), `---\ndescription: ${n} it\n---\n`);
  mkdirSync(join(dir, ".claude/commands"), { recursive: true });
  return dir;
}

test("no generated command takes the name of a Claude Code built-in", async () => {
  const dir = project();
  try {
    const cmds = join(dir, ".claude/commands");
    // A 7.11 install: the old shims, generated by Carja.
    writeFileSync(join(cmds, "ship.md"), "<!-- carja:generated-command -->\nold");
    writeFileSync(join(cmds, "status.md"), "<!-- carja:generated-command -->\nold");
    await generateClaudeCommands(dir);
    assert.equal(existsSync(join(cmds, "ship.md")), false, "old /ship removed");
    assert.equal(existsSync(join(cmds, "status.md")), false, "old /status removed");
    assert.match(readFileSync(join(cmds, "ship-it.md"), "utf8"), /`\.agents\/workflows\/ship\.md`/);
    assert.match(readFileSync(join(cmds, "carja-status.md"), "utf8"), /carja status/);
    assert.ok(existsSync(join(cmds, "build.md")), "other names unchanged");
    for (const b of CLAUDE_BUILTINS) assert.equal(existsSync(join(cmds, `${b}.md`)), false, `/${b} is a built-in`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("a command of the owner's own with a built-in name is left alone", async () => {
  const dir = project();
  try {
    writeFileSync(join(dir, ".claude/commands/ship.md"), "my own ship");
    await generateClaudeCommands(dir);
    assert.equal(readFileSync(join(dir, ".claude/commands/ship.md"), "utf8"), "my own ship");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
